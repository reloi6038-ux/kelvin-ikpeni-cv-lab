const byId = new Map(TEMPLATES.map((t) => [t.id, t]));

function list() {
  return TEMPLATES.map((t) => ({ ...t }));
}
function get(id) {
  const t = byId.get(id);
  return t ? { ...t } : null;
}
function isValidTemplateId(id) {
  return byId.has(id);
}

